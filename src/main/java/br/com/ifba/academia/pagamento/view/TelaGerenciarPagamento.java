    private void tblAlunosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblAlunosMouseClicked
        
        int linhaView = tblAlunos.getSelectedRow();
        if (linhaView == -1) return;

        int linhaModel = tblAlunos.convertRowIndexToModel(linhaView);
        Long id = (Long) modeloTabela.getValueAt(linhaModel, 0);

        try {
            Usuario usuario = usuarioService.findById(id);
            alunoSelecionado = usuario.getPessoa(); 
            planoSelecionado = null;

            List<br.com.ifba.academia.planoaluno.entity.PlanoAluno> matriculas = planoAlunoService.findAll();
            for (br.com.ifba.academia.planoaluno.entity.PlanoAluno matricula : matriculas) {
                if (matricula.getAluno().getId().equals(alunoSelecionado.getId())) {
                    planoSelecionado = matricula.getPlano();
                    break;
                }
            }

            if (planoSelecionado == null) {
                javax.swing.JOptionPane.showMessageDialog(this, "Atenção: Este aluno não possui uma matrícula ativa! Cadastre-o em um plano primeiro.", "Aluno Sem Matrícula", javax.swing.JOptionPane.WARNING_MESSAGE);
                tblAlunos.clearSelection();
                alunoSelecionado = null;
                cbxPlanos.removeAllItems();
                cbxPlanos.addItem("Selecione um aluno na tabela...");
            } else {
                cbxPlanos.removeAllItems();
                cbxPlanos.addItem(planoSelecionado.getNome() + " - R$ " + planoSelecionado.getValor());
                cbxPlanos.setSelectedIndex(0);
            }
            
            atualizarResumo();
            
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao buscar matrícula: " + e.getMessage());
        }
    }//GEN-LAST:event_tblAlunosMouseClicked

    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        
        if (alunoSelecionado == null) {
            JOptionPane.showMessageDialog(this, "Selecione um aluno na tabela!");
            return;
        }
        if (planoSelecionado == null) {
            JOptionPane.showMessageDialog(this, "Selecione um plano válido!");
            return;
        }
        
        String formaPag = cbxFormaPagamento.getSelectedItem().toString();

        try {
            br.com.ifba.academia.pagamento.entity.Pagamento pagamento = new br.com.ifba.academia.pagamento.entity.Pagamento();
            pagamento.setAluno(alunoSelecionado);
            pagamento.setValor(planoSelecionado.getValor());
            pagamento.setFormaPagamento(formaPag);
            pagamento.setDataPagamento(java.time.LocalDate.now());
            
            pagamentoService.save(pagamento);
            JOptionPane.showMessageDialog(this, "Pagamento registrado com sucesso!");
            
            alunoSelecionado = null;
            planoSelecionado = null;
            cbxPlanos.removeAllItems();
            cbxPlanos.addItem("Selecione um aluno na tabela...");
            tblAlunos.clearSelection();
            atualizarResumo();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao salvar pagamento: " + e.getMessage());
        }
        
    }//GEN-LAST:event_btnConfirmarActionPerformed

