    private void inicializarTabela() {
        modeloTabela = new DefaultTableModel(
            new Object[][] {},
            new String[] {"ID", "Nome", "CPF", "Telefone"}
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; 
            }
        };
        tblAlunos.setModel(modeloTabela);
        sorter = new TableRowSorter<>(modeloTabela);
        tblAlunos.setRowSorter(sorter);
    }

    public void preencherTabela() {
        modeloTabela.setRowCount(0);
        try {
            List<Usuario> lista = usuarioService.findAll();
            for (Usuario u : lista) {
                if ("ALUNO".equals(u.getPerfil())) {
                    modeloTabela.addRow(new Object[]{
                        u.getId(), u.getPessoa().getNome(), u.getPessoa().getCpf(),
                        u.getPessoa().getTelefone()
                    });
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao listar alunos: " + e.getMessage());
        }
    }

    
   private void atualizarResumo() {
        if (lblResumo == null) return;
        
        if (alunoSelecionado != null && planoSelecionado != null) {
            lblResumo.setText(String.format("Aluno: %s | Plano: %s | Receber: R$ %.2f", 
                    alunoSelecionado.getNome(), 
                    planoSelecionado.getNome(), 
                    planoSelecionado.getValor()));
            lblResumo.setForeground(new java.awt.Color(0, 153, 0));
        } else {
            lblResumo.setText("Selecione um aluno matriculado para continuar.");
            lblResumo.setForeground(java.awt.Color.RED);
        }
    }
   
   private void configurarFiltroDinamico() {
        txtPesquisa.getDocument().addDocumentListener(new DocumentListener() {
            @Override
            public void insertUpdate(DocumentEvent e) {
                filtrar();
            }
            
            @Override
            public void removeUpdate(DocumentEvent e) {
                filtrar();
            }
            
            @Override
            public void changedUpdate(DocumentEvent e) {
                filtrar();
            }

            private void filtrar() {
                String texto = txtPesquisa.getText();
                if (texto.trim().length() == 0) {
                    sorter.setRowFilter(null);
                } else {
                    sorter.setRowFilter(RowFilter.regexFilter("(?i)" + texto, 1));
                }
            }
        });
    }
   
   private void preencherComboFormasPagamento() {
        if (cbxFormaPagamento == null) return;
        
        cbxFormaPagamento.removeAllItems();
        cbxFormaPagamento.addItem("Dinheiro");
        cbxFormaPagamento.addItem("PIX");
        cbxFormaPagamento.addItem("Cartão de Crédito");
        cbxFormaPagamento.addItem("Cartão de Débito");
    }
   
