    private void btnCancelarMatriculaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelarMatriculaActionPerformed

        int linhaSelecionada = tblMatriculas.getSelectedRow();
        
        if (linhaSelecionada == -1) {
            JOptionPane.showMessageDialog(this, "Selecione uma matrícula na tabela para cancelar.");
            return;
        }

        Long idMatricula = (Long) tblMatriculas.getValueAt(linhaSelecionada, 0);

        int confirmacao = JOptionPane.showConfirmDialog(this, "Deseja realmente cancelar o plano deste aluno?", "Aviso", JOptionPane.YES_NO_OPTION);
        
        if (confirmacao == JOptionPane.YES_OPTION) {
            try {
                planoAlunoService.delete(idMatricula);
                JOptionPane.showMessageDialog(this, "Matrícula cancelada com sucesso.");
                atualizarTabela();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Erro ao cancelar: " + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnCancelarMatriculaActionPerformed

