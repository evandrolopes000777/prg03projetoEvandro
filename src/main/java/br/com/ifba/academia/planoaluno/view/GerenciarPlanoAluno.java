    private void atualizarTabela() {
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblMatriculas.getModel();
        
        modelo.setColumnIdentifiers(new Object[]{"ID", "Aluno", "Plano", "Início", "Vencimento"});
        modelo.setRowCount(0);

        try {
            List<PlanoAluno> matriculas = planoAlunoService.findAll();
            
            for (PlanoAluno mat : matriculas) {
                modelo.addRow(new Object[]{
                    mat.getId(),
                    mat.getAluno().getNome(),
                    mat.getPlano().getNome(),
                    mat.getDataInicio(),
                    mat.getDataVencimento()
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao buscar matrículas: " + e.getMessage());
        }
    }
