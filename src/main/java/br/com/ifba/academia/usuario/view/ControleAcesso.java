    private void inicializarTabela() {
        modeloTabela = new DefaultTableModel(
            new Object[][] {},
            new String[] {"ID", "Nome", "CPF", "Status Conta"}
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; 
            }
        };
        tblPessoas.setModel(modeloTabela);
        
        sorter = new TableRowSorter<>(modeloTabela);
        tblPessoas.setRowSorter(sorter);
    }

    private void preencherTabela() {
        modeloTabela.setRowCount(0);
        try {
            List<Pessoa> lista = pessoaService.findAll();
            for (Pessoa p : lista) {
                
                boolean isFlagAdmin = (p.getIsAdministrador() != null && p.getIsAdministrador());
                boolean isAdminPadrao = (p.getCpf() != null && p.getCpf().equals("00000000000"));
                boolean isNomeAdmin = (p.getNome() != null && p.getNome().equalsIgnoreCase("Administrador Padrão"));
                
                if (isFlagAdmin || isAdminPadrao || isNomeAdmin) {
                    continue; 
                }
                
                modeloTabela.addRow(new Object[]{
                    p.getId(), 
                    p.getNome(), 
                    p.getCpf(),
                    p.getAtivo()
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao carregar dados: " + e.getMessage());
        }
    }

    private void configurarFiltroDinamico() {
        DocumentListener ouvinteFiltro = new DocumentListener() {
            @Override
            public void insertUpdate(DocumentEvent e) { filtrar(); }
            @Override
            public void removeUpdate(DocumentEvent e) { filtrar(); }
            @Override
            public void changedUpdate(DocumentEvent e) { filtrar(); }
        };

        txtPesquisaId.getDocument().addDocumentListener(ouvinteFiltro);
        txtPesquisaNome.getDocument().addDocumentListener(ouvinteFiltro);
    }

    private void filtrar() {
        String textoId = txtPesquisaId.getText().trim();
        String textoNome = txtPesquisaNome.getText().trim();

        List<RowFilter<Object, Object>> filtros = new ArrayList<>();

        if (!textoId.isEmpty()) {
            filtros.add(RowFilter.regexFilter("^" + textoId + "$", 0));
        }
        
        if (!textoNome.isEmpty()) {
            filtros.add(RowFilter.regexFilter("(?i)" + textoNome, 1));
        }

        if (filtros.isEmpty()) {
            sorter.setRowFilter(null);
        } else {
            sorter.setRowFilter(RowFilter.andFilter(filtros));
        }
    }
