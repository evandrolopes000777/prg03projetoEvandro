    private void btnVerificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVerificarActionPerformed
       int linhaView = tblPessoas.getSelectedRow();
        
        if (linhaView == -1) {
            JOptionPane.showMessageDialog(this, "Por favor, selecione uma pessoa na tabela primeiro.");
            return;
        }

        int linhaModel = tblPessoas.convertRowIndexToModel(linhaView);
        
        Long idAluno = (Long) modeloTabela.getValueAt(linhaModel, 0);
        Boolean pessoaAtiva = (Boolean) modeloTabela.getValueAt(linhaModel, 3);

        if (!pessoaAtiva) {
            lblStatus.setText("BLOQUEADO (CONTA INATIVA)");
            lblStatus.setForeground(Color.RED);
            return;
        }

        boolean possuiMatriculaValida = false;
        
        try {
            List<PlanoAluno> todosPlanos = planoAlunoService.findAll();
            
            for (PlanoAluno plano : todosPlanos) {
                if (plano.getAluno().getId().equals(idAluno) && plano.getAtivo()) {
                    possuiMatriculaValida = true;
                    break;
                }
            }

            if (!possuiMatriculaValida) {
                lblStatus.setText("BLOQUEADO (SEM MATRÍCULA)");
                lblStatus.setForeground(Color.RED); 
                return; 
            }
            
            boolean pagamentoEmDia = false;
            List<Pagamento> todosPagamentos = pagamentoService.findAll();
            
            java.time.LocalDate trintaDiasAtras = java.time.LocalDate.now().minusDays(30);
            
            for (Pagamento pag : todosPagamentos) {
                if (pag.getAluno().getId().equals(idAluno) && pag.getAtivo()) {
                    if (!pag.getDataPagamento().isBefore(trintaDiasAtras)) {
                        pagamentoEmDia = true;
                        break;
                    }
                }
            }

            if (pagamentoEmDia) {
                lblStatus.setText("LIBERADO");
                lblStatus.setForeground(new java.awt.Color(0, 153, 0));
            } else {
                lblStatus.setText("BLOQUEADO (INADIMPLENTE)");
                lblStatus.setForeground(Color.RED);
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao verificar acesso: " + e.getMessage());
            lblStatus.setText("ERRO DE CONEXÃO");
            lblStatus.setForeground(Color.ORANGE);
        }
    }//GEN-LAST:event_btnVerificarActionPerformed

