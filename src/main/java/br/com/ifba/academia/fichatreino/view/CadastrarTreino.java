    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        
       if (cbxAlunos.getSelectedIndex() == 0 || txtDescricao.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Preencha a descrição e selecione um aluno!");
            return;
        }

        try {
            FichaTreino ficha = (this.fichaEdicao != null) ? this.fichaEdicao : new FichaTreino();
            ficha.setDescricao(txtDescricao.getText());
            
            if (ficha.getId() == null) {
                ficha.setDataCriacao(LocalDate.now());
                ficha.setAtivo(true);
            }
            
            Pessoa alunoSelecionado = alunosCadastrados.get(cbxAlunos.getSelectedIndex() - 1);
            ficha.setAluno(alunoSelecionado);

            
            if (ficha.getItens() == null) {
                ficha.setItens(new ArrayList<>());
            } else {
                List<ItemFicha> itensAntigos = new ArrayList<>(ficha.getItens());
                for (ItemFicha itemAntigo : itensAntigos) {
                    ficha.removerItem(itemAntigo); 
                }
            }

            for (int i = 0; i < modeloTreino.getRowCount(); i++) {
                Long exId = Long.parseLong(modeloTreino.getValueAt(i, 0).toString());
                Exercicio ex = exercicioService.findById(exId);
                
                ItemFicha item = new ItemFicha();
                item.setExercicio(ex);
                item.setSeries(Integer.parseInt(modeloTreino.getValueAt(i, 2).toString()));
                item.setRepeticoes(Integer.parseInt(modeloTreino.getValueAt(i, 3).toString()));
                item.setCarga(Double.parseDouble(modeloTreino.getValueAt(i, 4).toString()));
                
                ficha.adicionarItem(item);
            }

            
            if (ficha.getId() == null) {
                fichaTreinoService.save(ficha);
                JOptionPane.showMessageDialog(this, "Treino cadastrado com sucesso!");
            } else {
                fichaTreinoService.update(ficha);
                JOptionPane.showMessageDialog(this, "Treino atualizado com sucesso!");
            }

            this.dispose();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao salvar treino: " + e.getMessage());
        }
        
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void tblTreinoMontadoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblTreinoMontadoMouseClicked
        
        int linha = tblTreinoMontado.getSelectedRow();
        int coluna = tblTreinoMontado.columnAtPoint(evt.getPoint());
        if (linha == -1) return;

        if (coluna >= 2 && coluna <= 4) {
            String titulo = tblTreinoMontado.getColumnName(coluna);
            String valorAtual = tblTreinoMontado.getValueAt(linha, coluna).toString();
            String novoValor = JOptionPane.showInputDialog(this, "Definir " + titulo + ":", valorAtual);
            
            if (novoValor != null && !novoValor.trim().isEmpty()) {
                try {
                    if (coluna == 4) Double.parseDouble(novoValor); else Integer.parseInt(novoValor);
                    tblTreinoMontado.setValueAt(novoValor, linha, coluna);
                } catch (NumberFormatException e) {
                    JOptionPane.showMessageDialog(this, "Por favor, digite um número válido.");
                }
            }
        } else if (coluna == 5) {
            modeloTreino.removeRow(linha);
        }
        
    }//GEN-LAST:event_tblTreinoMontadoMouseClicked

