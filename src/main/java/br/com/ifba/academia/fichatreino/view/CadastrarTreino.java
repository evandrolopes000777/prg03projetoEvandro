    private void inicializarTabelas() {
        //tabela de exerc.
        modeloBanco = new DefaultTableModel(new Object[][]{}, new String[]{"ID", "Nome", "Músculo", "Ação"}) {
            @Override
            public boolean isCellEditable(int row, int column) { return false; }
        };
        tblBancoExercicios.setModel(modeloBanco);
        sorterBanco = new TableRowSorter<>(modeloBanco);
        tblBancoExercicios.setRowSorter(sorterBanco);

        //tabela do treino sendo montado 
        modeloTreino = new DefaultTableModel(new Object[][]{}, new String[]{"ID Exercicio", "Exercício", "Séries", "Repetições", "Carga(kg)", "Ação"}) {
            @Override
            public boolean isCellEditable(int row, int column) { return false; }
        };
        tblTreinoMontado.setModel(modeloTreino);
    }
    
    private void carregarComboboxAlunos() {
        cbxAlunos.removeAllItems();
        cbxAlunos.addItem("Selecione um Aluno");
        
        alunosCadastrados = new ArrayList<>();
        List<Pessoa> todasPessoas = pessoaService.findAll();
        
        if (todasPessoas == null) {
            return;
        }
        
        for (Pessoa p : todasPessoas) {
            if (p == null) {
                continue;
            }
            
            boolean isAdmin = p.getIsAdministrador() != null && p.getIsAdministrador();
            boolean isAdminPadrao = p.getCpf() != null && p.getCpf().equals("00000000000");
            boolean isNomeAdmin = p.getNome() != null && p.getNome().equalsIgnoreCase("Administrador Padrão");
            boolean isAtivo = p.getAtivo() != null && p.getAtivo();
            
            if (isAdmin || isAdminPadrao || isNomeAdmin || !isAtivo) {
                continue;
            }
            
            alunosCadastrados.add(p);
            cbxAlunos.addItem(p.getNome() + " - " + p.getCpf());
        }
    }

    private void carregarBancoExercicios() {
        modeloBanco.setRowCount(0);
        List<Exercicio> exercicios = exercicioService.findAll();
        for (Exercicio ex : exercicios) {
            if (ex.getAtivo()) {
                modeloBanco.addRow(new Object[]{ex.getId(), ex.getNome(), ex.getGrupoMuscular(), "➕ ADICIONAR"});
            }
        }
    }
    
    public void preencherCamposParaEdicao(FichaTreino ficha) {
        this.fichaEdicao = ficha;
        txtDescricao.setText(ficha.getDescricao());
        btnSalvar.setText("Salvar Alterações");
        
        for (int i = 0; i < alunosCadastrados.size(); i++) {
            if (alunosCadastrados.get(i).getId().equals(ficha.getAluno().getId())) {
                cbxAlunos.setSelectedIndex(i + 1);
                break;
            }
        }
        
        modeloTreino.setRowCount(0);
        for (ItemFicha item : ficha.getItens()) {
            modeloTreino.addRow(new Object[]{
                item.getExercicio().getId(),
                item.getExercicio().getNome(),
                item.getSeries(),
                item.getRepeticoes(),
                item.getCarga(),
                "❌ Remover"
            });
        }
    }
    
    private void configurarFiltroExercicios() {
        txtPesquisarExercicio.getDocument().addDocumentListener(new DocumentListener() {
            @Override
            public void insertUpdate(DocumentEvent e) { sorterBanco.setRowFilter(RowFilter.regexFilter("(?i)" + txtPesquisarExercicio.getText(), 1)); }
            @Override
            public void removeUpdate(DocumentEvent e) { sorterBanco.setRowFilter(RowFilter.regexFilter("(?i)" + txtPesquisarExercicio.getText(), 1)); }
            @Override
            public void changedUpdate(DocumentEvent e) { sorterBanco.setRowFilter(RowFilter.regexFilter("(?i)" + txtPesquisarExercicio.getText(), 1)); }
        });
    }
