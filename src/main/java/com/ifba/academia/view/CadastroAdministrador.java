    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        
        String nomeDigitado = txtNome.getText();
        String usuarioDigitado = txtUsuario.getText();
        String senhaDigitada = txtSenha.getText();
        
        if (nomeDigitado.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, preencha o campo nome.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (usuarioDigitado.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, preencha o campo usuário.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (senhaDigitada.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, preencha o campo senha.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        try {
            com.ifba.academia.model.Administrador administrador;
            
            if (this.adminEmEdicao != null) {
                administrador = this.adminEmEdicao;
            } else {
                administrador = new com.ifba.academia.model.Administrador();
            }
            
            administrador.setNome(nomeDigitado);
            administrador.setLogin(usuarioDigitado); 
            administrador.setSenha(senhaDigitada);

            this.administradorService.salvar(administrador);

            javax.swing.JOptionPane.showMessageDialog(this, "Administrador salvo com sucesso!");

            txtNome.setText("");
            txtUsuario.setText("");
            txtSenha.setText("");
            
            this.adminEmEdicao = null;

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao salvar: " + e.getMessage(), "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
        }  
        
    }//GEN-LAST:event_btnSalvarActionPerformed

